#!/usr/bin/env bash
# Regenerates THIRD_PARTY_LICENSES.md: every licence text of the Rust crates
# compiled into the desktop binary and the npm packages bundled into its UI.
# Needs cargo-about (CARGO_ABOUT_VERSION below) and node_modules from `npm ci`.
# CI runs this and fails if the committed file differs, so re-run it after any
# dependency change.
set -euo pipefail

CARGO_ABOUT_VERSION="0.9.2"
LICENSE_CHECKER_VERSION="25.0.1"

cd "$(dirname "$0")/.."
out="THIRD_PARTY_LICENSES.md"

if ! cargo about --version 2>/dev/null | grep -q "$CARGO_ABOUT_VERSION"; then
  echo "cargo-about $CARGO_ABOUT_VERSION is required:" >&2
  echo "  cargo install cargo-about --locked --features cli --version $CARGO_ABOUT_VERSION" >&2
  exit 1
fi

{
  echo "# Third-party licences"
  echo
  echo "Nodea Desktop is licensed under Apache-2.0 (see LICENSE and NOTICE). It"
  echo "includes the third-party software below, each under its own licence."
  echo "This file is generated by scripts/generate-third-party-licenses.sh; do not"
  echo "edit it by hand."
  echo
  (cd src-tauri && cargo about generate --locked --fail about.hbs)
  npx --yes "license-checker@${LICENSE_CHECKER_VERSION}" --production --json \
    | node scripts/npm-licenses.mjs
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "Wrote $out"
